CREATE TABLE photos
(
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_in_cloud varchar(255) NOT NULL,
    url         varchar(255) NOT NULL
);

CREATE TABLE regions
(
    id   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(100) NOT NULL UNIQUE
);

CREATE TABLE towns
(
    id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    region_id bigint       NOT NULL REFERENCES regions (id),
    name      varchar(100) NOT NULL
);

CREATE TABLE roles
(
    id   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(20) NOT NULL UNIQUE CHECK (name IN ('ROLE_USER', 'ROLE_MODERATOR', 'ROLE_ADMIN', 'ROLE_ROOT'))
);

CREATE TABLE profiles
(
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    connected    boolean NOT NULL DEFAULT false,
    is_completed boolean NOT NULL DEFAULT false,
    photo_id     bigint UNIQUE REFERENCES photos (id),
    town_id      bigint REFERENCES towns (id),
    about_me     varchar(100),
    first_name   varchar(12),
    last_name    varchar(12)
);

CREATE TABLE users
(
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    profile_id bigint       NOT NULL UNIQUE REFERENCES profiles (id),
    email      varchar(255) NOT NULL UNIQUE,
    password   varchar(255) NOT NULL,
    username   varchar(12)  NOT NULL UNIQUE
);

CREATE TABLE users_roles
(
    user_id bigint NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    role_id bigint NOT NULL REFERENCES roles (id),
    PRIMARY KEY (user_id, role_id)
);

CREATE TABLE categories
(
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    creator_id bigint REFERENCES profiles (id),
    photo_id   bigint      NOT NULL UNIQUE REFERENCES photos (id),
    name       varchar(50) NOT NULL UNIQUE
);

CREATE TABLE advertisements
(
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title         varchar(20)    NOT NULL,
    description   varchar(1000)  NOT NULL,
    price         numeric(10, 2) NOT NULL CHECK (price >= 0),
    state         varchar(20)    NOT NULL CHECK (state IN ('USED', 'NEW', 'BROKEN')),
    delivery_type varchar(20)    NOT NULL CHECK (delivery_type IN ('COURIER', 'NONE', 'NEGOTIATING')),
    views         bigint         NOT NULL DEFAULT 0 CHECK (views >= 0),
    created_on    timestamp(6)   NOT NULL,
    category_id   bigint         NOT NULL REFERENCES categories (id),
    creator_id    bigint         NOT NULL REFERENCES profiles (id)
);
CREATE INDEX idx_advertisements_category ON advertisements (category_id);
CREATE INDEX idx_advertisements_creator ON advertisements (creator_id);
CREATE INDEX idx_advertisements_price ON advertisements (price);

CREATE TABLE advertisement_photo
(
    advertisement_id bigint NOT NULL REFERENCES advertisements (id) ON DELETE CASCADE,
    photo_id         bigint NOT NULL UNIQUE REFERENCES photos (id),
    PRIMARY KEY (advertisement_id, photo_id)
);

CREATE TABLE profiles_favorites
(
    profile_id           bigint NOT NULL REFERENCES profiles (id) ON DELETE CASCADE,
    fav_advertisement_id bigint NOT NULL REFERENCES advertisements (id) ON DELETE CASCADE,
    PRIMARY KEY (profile_id, fav_advertisement_id)
);

CREATE TABLE profiles_viewed
(
    profile_id              bigint NOT NULL REFERENCES profiles (id) ON DELETE CASCADE,
    viewed_advertisement_id bigint NOT NULL REFERENCES advertisements (id) ON DELETE CASCADE,
    PRIMARY KEY (profile_id, viewed_advertisement_id)
);

CREATE TABLE channels
(
    id varchar(25) PRIMARY KEY
);

CREATE TABLE profiles_channels
(
    profile_id bigint      NOT NULL REFERENCES profiles (id) ON DELETE CASCADE,
    channel_id varchar(25) NOT NULL REFERENCES channels (id) ON DELETE CASCADE,
    PRIMARY KEY (profile_id, channel_id)
);

CREATE TABLE chat_messages
(
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sender_id   bigint        NOT NULL REFERENCES profiles (id),
    channel_id  varchar(25)   NOT NULL REFERENCES channels (id),
    content     varchar(1000) NOT NULL,
    "timestamp" timestamp(6)  NOT NULL,
    read_date   timestamp(6)
);
CREATE INDEX idx_chat_messages_channel ON chat_messages (channel_id, "timestamp" DESC);

